	expect_selects_like_tidyselect(starts_with("x") & !x1)
	expect_selects_like_tidyselect(c(starts_with("x"), -x2))
	expect_selects_like_tidyselect(c(id, starts_with("x"), -x2, x2))
	expect_selects_like_tidyselect(c(id, -starts_with("x")))
	expect_selects_like_tidyselect(ends_with("1") | ends_with("2"))
	expect_selects_like_tidyselect(starts_with("x"):last_col())
})

